let preferences = { ...DEFAULTS };

export function hydratePreferences(value: UiPreferences): void {
  preferences = { ...value };
}

export function getPreferences(): UiPreferences { return { ...preferences }; }
export function getLanguage(): UiLanguage { return preferences.language; }
export function t(key: string, vars: Record<string, string | number> = {}): string {
  const dict = preferences.language === "en" ? en : zh;
  let text = dict[key] ?? zh[key] ?? key;
  for (const [name, value] of Object.entries(vars)) text = text.replaceAll(`{${name}}`, String(value));
  return text;
}
export function applyPreferences(hostTheme?: "light" | "dark"): void {
  if (typeof document === "undefined") return;
  const theme = preferences.theme === "system"
    ? hostTheme ?? (typeof window !== "undefined" && window.matchMedia?.("(prefers-color-scheme: light)").matches ? "light" : "dark")
    : preferences.theme;
  document.documentElement.dataset.theme = theme;
  document.documentElement.toggleAttribute("data-local-theme", preferences.theme !== "system");
  document.documentElement.lang = preferences.language;
  document.documentElement.classList.toggle("reduce-motion", !preferences.animatedAvatars);
}
